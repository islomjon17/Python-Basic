# Uy ishi (return + shartlar, xatolik, statistika)

# 1. Shartli baholash
# Foydalanuvchining balli va imtihonga kechikishi (True/False) parametrlarini qabul qiladigan funksiya yozing va ball asosida quyidagi baholarni qaytaring:

# 90–100 → “A”

# 80–89 → “B”

# 70–79 → “C”

# 0–69 → “F”

# Noto‘g‘ri ball → “Xato ball”

# 2. Xatolikni return orqali tekshirish
# Ikki sonni bo‘lishni bajaruvchi funksiya yozing. Agar bo‘luvchi 0 bo‘lsa, "0 ga bo‘lish mumkin emas" qaytarsin, aks holda natijani qaytarsin.

# 3. Ro‘yxatdan topish
# Ro‘yxat va qidirilayotgan elementni parametr sifatida qabul qiluvchi funksiya yozing. Element topilsa True, topilmasa False qaytarsin.

# 4. Foydalanuvchi validatsiyasi
# Login va parol qabul qiluvchi funksiya yozing. Quyidagi shartlarni tekshirsin:

# Login 5 belgidan kam bo‘lsa → "Login juda qisqa"

# Parol 8 belgidan kam bo‘lsa → "Parol kuchsiz"

# Parol faqat raqam bo‘lsa → "Parolda kamida bitta harf bo‘lishi kerak"

# Boshqa holatda → "Ruxsat berildi"

# 5. Statistika
# Berilgan sonlar ro‘yxati bo‘yicha: jami, o‘rtacha, maksimum va minimum qiymatlarni lug‘at ko‘rinishida qaytaruvchi funksiya yozing.

# 6. Maxsus mashq (uy ishi qo‘shimcha)
# Ro‘yxatdagi musbat sonlarni hisoblovchi funksiya yozing. Agar ro‘yxat bo‘sh bo‘lsa, None qaytarsin.

# 7. Return bilan early exit
# Foydalanuvchi yoshini qabul qiluvchi funksiya yozing. Agar yosh 0 dan kichik yoki 120 dan katta bo‘lsa, "Noto‘g‘ri yosh" qaytarsin. Aks holda "Yosh qabul qilindi" deb qaytarsin.